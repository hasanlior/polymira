let flat: Record<string, string> | null = null
/** Dictionary keyed by whitespace-collapsed text (for keys that contain line breaks). */
function EN_FLAT(): Record<string, string> {
  if (!flat) flat = Object.fromEntries(Object.entries(EN).map(([k, v]) => [k.replace(/\s+/g, ' '), v]))
  return flat
}

export function translate(text: string, lang: string): string {
  if (lang !== 'en' || !text) return text
  const trimmed = text.trim().replace(/\s+/g, ' ')
  if (!trimmed) return text
  const exact = EN[trimmed] ?? EN_FLAT()[trimmed]
  if (exact !== undefined) return text.replace(text.trim(), exact)
  for (const [re, out] of PATTERNS) {
    if (re.test(trimmed)) {
      // Captured parts are translated too (e.g. "3 oyun · Kararlı" → "3 games · Stable").
      const done = trimmed.replace(re, (...m: string[]) => out.replace(/\$(\d)/g, (_, n: string) => translate(m[Number(n)] ?? '', lang)))
      return text.replace(text.trim(), done)
    }
  }
  // Lines built from parts ("PlayStation 2 · 6 sa 0 dk"): translate each part.
  if (trimmed.includes(' · ')) {
    const parts = trimmed.split(' · ')
    const done = parts.map((p) => translate(p, lang))
    if (done.some((p, i) => p !== parts[i])) return text.replace(text.trim(), done.join(' · '))
  }
  return text
}

let current = 'tr'

/** Locale for dates and numbers in the current interface language. */
export function locale(): string {
  return current === 'en' ? 'en-GB' : 'tr-TR'
}
let observer: MutationObserver | null = null
const ATTRS = ['placeholder', 'title', 'aria-label']

function translateNode(node: Node): void {
  if (node.nodeType === Node.TEXT_NODE) {
    const v = node.nodeValue ?? ''
    const t = translate(v, current)
    if (t !== v) node.nodeValue = t
    return
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return
  const el = node as Element
  if (el.tagName === 'SCRIPT' || el.tagName === 'STYLE' || el.tagName === 'WEBVIEW') return
  for (const a of ATTRS) {
    const v = el.getAttribute(a)
    if (v) {
      const t = translate(v, current)
      if (t !== v) el.setAttribute(a, t)
    }
  }
  for (const child of Array.from(el.childNodes)) translateNode(child)
}

/**
 * Applies the interface language to the whole page and keeps it applied as the page changes.
 * Switching back to Turkish reloads the page so every text is rendered from the source again.
 */
export function applyLanguage(lang: 'tr' | 'en'): void {
  if (lang === current) return
  const wasEn = current === 'en'
  current = lang
  document.documentElement.lang = lang
  if (lang === 'en') {
    translateNode(document.body)
    observer = new MutationObserver((records) => {
      for (const r of records) {
        if (r.type === 'characterData') translateNode(r.target)
        else if (r.type === 'attributes') translateNode(r.target)
        else r.addedNodes.forEach(translateNode)
      }
    })
    observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS })
  } else if (wasEn) {
    observer?.disconnect()
    observer = null
    location.reload()
  }
}
